#!/usr/bin/env python3
"""Cuts the icons this program uses out of the Lucide font.

Lucide ships 2034 icons in a 858 KB font. Shipping all of them to draw a
dozen would be most of a megabyte of glyphs nobody will ever see, so the
whole font is fetched, the ones named in ICONS are cut out of it, and the
rest is thrown away — a few hundred bytes each.

The same list also writes the Rust constants, and that is the point of doing
both here: a name and a code point that live in two files drift, and a drifted
icon is a blank box on a button with nothing to say what went wrong.

    ./scripts/lucide.py

Needs `fonttools` (`pip install fonttools`) and the network. Run it after
adding a name to ICONS, and commit what it writes.
"""

import json
import pathlib
import subprocess
import sys
import urllib.request

VERSION = "1.33.0"
BASE = f"https://unpkg.com/lucide-static@{VERSION}"

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / "crates/cie-gui/fonts/lucide.ttf"
LICENCE = ROOT / "crates/cie-gui/fonts/LICENSE-lucide.txt"
RUST = ROOT / "crates/cie-gui/src/icon.rs"

# What the program draws, as (Lucide name, Rust constant, what it is for).
# Adding a line here and re-running is the whole of adding an icon.
ICONS = [
    ("align-left", "ALIGN_LEFT", "text against the left of its rectangle"),
    ("align-center", "ALIGN_CENTRE", "text centred in its rectangle"),
    ("align-right", "ALIGN_RIGHT", "text against the right of its rectangle"),
    ("align-start-horizontal", "ALIGN_TOP", "the picture at the top of its rectangle"),
    ("align-center-horizontal", "ALIGN_MIDDLE", "the picture halfway down it"),
    ("align-end-horizontal", "ALIGN_BOTTOM", "the picture at the bottom of it"),
    ("bold", "BOLD", "heavier type"),
    ("type", "SIZE", "the type size"),
    ("plus", "ADD", "one more template"),
    ("copy", "DUPLICATE", "this template again"),
    ("trash-2", "REMOVE", "take it out"),
    ("magnet", "SNAP", "latching on to the lines other pieces make"),
]


def fetch(path: str) -> bytes:
    with urllib.request.urlopen(f"{BASE}/{path}") as response:
        return response.read()


def main() -> int:
    print(f"lucide-static {VERSION}")

    info = json.loads(fetch("font/info.json"))
    missing = [name for name, _, _ in ICONS if name not in info]
    if missing:
        # Lucide renames icons between releases. Failing here with the name is
        # a great deal friendlier than shipping a font with a hole in it.
        print(f"not in this release of Lucide: {', '.join(missing)}", file=sys.stderr)
        return 1

    points = {
        name: int(info[name]["encodedCode"].lstrip("\\"), 16) for name, _, _ in ICONS
    }

    whole = ROOT / "target" / "lucide-whole.ttf"
    whole.parent.mkdir(parents=True, exist_ok=True)
    whole.write_bytes(fetch("font/lucide.ttf"))

    subprocess.run(
        [
            sys.executable,
            "-m",
            "fontTools.subset",
            str(whole),
            "--unicodes=" + ",".join(f"U+{points[n]:04X}" for n, _, _ in ICONS),
            f"--output-file={FONT}",
            "--no-hinting",
            "--drop-tables+=DSIG",
        ],
        check=True,
    )

    LICENCE.write_bytes(fetch("LICENSE"))

    lines = [
        "//! The icons on the buttons.",
        "//!",
        "//! Generated by `scripts/lucide.py` — do not edit. The font beside it",
        "//! carries these glyphs and no others, so a code point written by hand",
        "//! here would draw an empty box.",
        "",
        "use iced::Font;",
        "",
        "/// Lucide, cut down to the glyphs below. ISC — `fonts/LICENSE-lucide.txt`",
        "/// travels with it.",
        'pub const FONT: Font = Font::with_name("lucide");',
        "",
    ]
    for name, constant, what in ICONS:
        lines.append(f"/// `{name}` — {what}.")
        lines.append(f"pub const {constant}: char = '\\u{{{points[name]:x}}}';")
        lines.append("")

    RUST.write_text("\n".join(lines))

    print(f"{FONT.relative_to(ROOT)}  {FONT.stat().st_size} byte, {len(ICONS)} icone")
    print(f"{RUST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
